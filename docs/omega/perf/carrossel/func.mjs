import { chromium } from 'playwright-core';
import fs from 'node:fs';
const [url, label] = process.argv.slice(2);
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--host-resolver-rules=MAP loja.test 127.0.0.1', '--ignore-certificate-errors'] });
const p = await (await b.newContext({ viewport: { width: 412, height: 915 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, ignoreHTTPSErrors: true })).newPage();
const errs = []; p.on('pageerror', (e) => errs.push(String(e)));
await p.goto(url, { waitUntil: 'networkidle' }); await p.waitForSelector('.home-banner-track');
const sl = () => p.evaluate(() => Math.round(document.querySelector('.home-banner-track').scrollLeft));
const active = () => p.evaluate(() => [...document.querySelectorAll('.home-banner-dot')].findIndex((d) => d.classList.contains('active')));
const r = { url };
r.start = { scroll: await sl(), dot: await active() };
await p.waitForTimeout(6500);
r.afterAutoplay6_5s = { scroll: await sl(), dot: await active() };
await p.evaluate(() => window.scrollTo(0, 2500)); await p.waitForTimeout(12000);
r.offscreen12s = { scroll: await sl(), dot: await active() };
await p.evaluate(() => window.scrollTo(0, 0)); await p.waitForTimeout(300);
await p.locator('.home-banner-dot').nth(3).click(); await p.waitForTimeout(600);
r.dot3Click = { scroll: await sl(), dot: await active() };
r.slides = await p.locator('.home-banner-slide').count();
r.imgsLoaded = await p.evaluate(() => [...document.querySelectorAll('.home-banner-img')].filter((i) => i.complete && i.naturalWidth > 0).length);
r.jsErrors = errs;
fs.writeFileSync(`/workspace/ls-final-evidence/carousel/func-${label}.json`, JSON.stringify(r, null, 2));
console.log(JSON.stringify(r));
await b.close();
